/**
 * Chaves de i18n para os exportadores de PDF do Gap Analysis e para os
 * blocos de onboarding por framework que não possuem chave equivalente
 * em `gap-analysis.ts`.
 *
 * Os exportadores de PDF (ExportBoardPDF/ExportFrameworkPDF/SoAExportPDF)
 * não são componentes React — não têm acesso ao hook `useLanguage`. Por
 * isso, além deste dicionário, expomos os helpers `getExportLocale` e
 * `interpolateExport`, usados diretamente nesses arquivos junto com o
 * dicionário `gapAnalysis.pdfExport` (já existente em `gap-analysis.ts`).
 */
import type { Locale } from '@/contexts/LanguageContext';

const STORAGE_KEY = 'governaii-locale';

export function getExportLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'pt') return saved;
    const browserLang = navigator.language || '';
    return browserLang.startsWith('pt') ? 'pt' : 'en';
  } catch {
    return 'pt';
  }
}

export function interpolateExport(str: string, params?: Record<string, string | number>): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

